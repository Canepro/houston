"""`houston/runner.py`'s on-disk state: what survives an interruption, and in what order.

A workspace is a directory, and the only thing that makes it one is `repro.json`. Each
write in `runner.write` is individually atomic; the PAIR is not, so which half a killed
process leaves behind is decided entirely by the order of two lines -- and that order
has no other symptom. Nothing here needs Docker.
"""
from __future__ import annotations

import pytest


def test_the_record_is_written_before_the_compose_file(tmp_path, monkeypatch):
    """Which half survives a kill is decided by this order. The record is what makes
    a directory a workspace; the compose document is regenerated by `up` anyway."""
    from houston import runner as runnersvc

    monkeypatch.setenv("HOUSTON_HOME", str(tmp_path))
    order: list[str] = []
    real = runnersvc.atomic_write
    monkeypatch.setattr(runnersvc.paths, "atomic_write",
                        lambda p, c, **k: order.append(p.name) or real(p, c, **k))
    meta = runnersvc.Metadata(name="ordered", project="p", rc_version="8.5.1",
                              rc_image="i", mongo_tag="7.0", mongo_flavor="official",
                              preset="default", root_url="http://localhost:3000",
                              host_port=3000, version_source="x")
    runnersvc.write("ordered", "services: {}\n", meta)
    assert order[:2] == ["repro.json", "docker-compose.yml"], order


def test_a_kill_between_the_two_writes_leaves_the_half_that_can_be_read(tmp_path,
                                                                       monkeypatch):
    """The order is only worth having if the survivor is usable, so kill between them.

    Each write is individually atomic; the PAIR is not, and a directory with one of the
    two in it is a directory `exists()` accepts. Compose-first leaves the half
    `read_meta` cannot read and `list_meta` skips — a workspace invisible to `list`,
    `prune` and port allocation while still holding its name. Record-first leaves the
    half that is fully visible and whose compose file `up` regenerates anyway.

    Asserted on the survivor rather than on the call order, because the order is the
    mechanism and this is the property.
    """
    from houston import errors
    from houston import runner as runnersvc

    monkeypatch.setenv("HOUSTON_HOME", str(tmp_path))
    real = runnersvc.atomic_write

    def killed(path, content, **kw):
        if path.name == "docker-compose.yml":
            raise KeyboardInterrupt("killed between the two writes")
        return real(path, content, **kw)

    monkeypatch.setattr(runnersvc.paths, "atomic_write", killed)
    meta = runnersvc.Metadata(name="halfway", project="p", rc_version="8.5.1",
                              rc_image="i", mongo_tag="7.0", mongo_flavor="official",
                              preset="default", root_url="http://localhost:3000",
                              host_port=3000, version_source="x")
    with pytest.raises(KeyboardInterrupt):
        runnersvc.write("halfway", "services: {}\n", meta)

    ws = tmp_path / "repros" / "halfway"
    assert (ws / "repro.json").is_file(), "the record did not survive the kill"
    assert not (ws / "docker-compose.yml").exists(), "precondition: the kill landed"
    # The survivor is USABLE: readable, and visible to everything that walks the home.
    assert runnersvc.read_meta("halfway").host_port == 3000
    assert "halfway" in [m.name for m in runnersvc.list_meta()]
    # And the other order would leave the half that raises here instead.
    with pytest.raises(errors.MissingRecordError):
        runnersvc.read_meta("no-such-record")
