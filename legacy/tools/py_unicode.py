#!/usr/bin/env python
"""Write `src/lib/py-unicode.ts` from the installed Python's own Unicode database.

    .venv/bin/python legacy/tools/py_unicode.py            # rewrite it, then format it

`int()` and `float()` read every Unicode decimal digit as its ASCII digit, and `repr()`
escapes every code point `str.isprintable()` refuses. Both answers come from the Unicode
database CPython was BUILT with -- 15.0.0 for the venv's 3.12 -- and not from the one
Node's ICU carries, which is 17.0 for Node 24. The two disagree on every code point
Unicode 16 and 17 assigned: 90 new decimal digits (U+116D0 is one) and 10,615 code points
Python still calls unassigned, so non-printable. A `\\p{Nd}` or `\\p{C}` test in
TypeScript is therefore a second opinion from a newer standard, and this script copies
Python's instead: `test/cli/click.test.ts` and `test/lib/pyformat.test.ts` fail when the
copy's DATA and the installed Python's disagree -- the data, not the text, because the
file is formatted by prettier.

`str.casefold()` is the third: the full case folding of the same database, which is not
`toLowerCase()` -- `ß` folds to `ss`, `ς` and `Σ` both to `σ`, `µ` to `μ`, and a Cherokee
small letter to its capital. `test/lib/pyformat.test.ts` holds that table to Python too.
"""
from __future__ import annotations

import pathlib
import platform
import subprocess
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / "src" / "lib" / "py-unicode.ts"


def decimal_runs() -> list[tuple[int, int, int]]:
    """`[first, last, value of first]` for every run of consecutive code points whose
    `unicodedata.decimal()` values are consecutive, so a run ends where the next zero
    starts -- the mathematical digits U+1D7CE..U+1D7FF are five runs, not one."""
    runs: list[list[int]] = []
    for point in range(sys.maxunicode + 1):
        value = unicodedata.decimal(chr(point), None)
        if value is None:
            continue
        if runs and runs[-1][1] == point - 1 and runs[-1][2] + point - runs[-1][0] == value:
            runs[-1][1] = point
        else:
            runs.append([point, point, value])
    return [(first, last, value) for first, last, value in runs]


def not_printable() -> list[tuple[int, int]]:
    """Inclusive ranges of the code points `str.isprintable()` refuses."""
    ranges: list[list[int]] = []
    for point in range(sys.maxunicode + 1):
        if chr(point).isprintable():
            continue
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return [(first, last) for first, last in ranges]


def case_folds() -> list[tuple[int, list[int]]]:
    """`[point, [folded code points]]` for every code point `str.casefold()` changes."""
    out: list[tuple[int, list[int]]] = []
    for point in range(sys.maxunicode + 1):
        folded = chr(point).casefold()
        if folded != chr(point):
            out.append((point, [ord(ch) for ch in folded]))
    return out


def render() -> str:
    digits = "\n".join(f"  [{first}, {last}, {value}]," for first, last, value in decimal_runs())
    hidden = "\n".join(f"  [{first}, {last}]," for first, last in not_printable())
    folds = "\n".join(f"  [{point}, {folded!r}]," for point, folded in case_folds())
    return f"""/**
 * GENERATED by `.venv/bin/python legacy/tools/py_unicode.py` from Python
 * {platform.python_version()}'s unicodedata, Unicode {unicodedata.unidata_version}. Do not edit: regenerate.
 * `test/cli/click.test.ts` and `test/lib/pyformat.test.ts` hold this copy to the installed
 * Python.
 */

/**
 * Every decimal digit, as runs: `[first, last, value of first]`, inclusive, each code
 * point after `first` one more than the one before it. `unicodedata.decimal()`.
 */
export const DECIMAL_DIGITS: readonly (readonly [number, number, number])[] = [
{digits}
];

/** Inclusive code point ranges `str.isprintable()` refuses, which `repr()` escapes. */
export const NOT_PRINTABLE: readonly (readonly [number, number])[] = [
{hidden}
];

/**
 * Every code point `str.casefold()` changes, beside the code points it folds to.
 * `pyCasefold` in `./pyformat`.
 */
export const CASE_FOLDS: readonly (readonly [number, readonly number[]])[] = [
{folds}
];

export const UNICODE_VERSION = {unicodedata.unidata_version!r};
"""


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8")
    subprocess.run([str(ROOT / "node_modules" / ".bin" / "prettier"), "--write", str(TARGET)],
                   check=True, capture_output=True)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
