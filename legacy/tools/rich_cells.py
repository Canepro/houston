#!/usr/bin/env python
"""Write `src/cli/rich-cells.ts` from the installed Rich's own cell-width table.

    .venv/bin/python legacy/tools/rich_cells.py            # rewrite it, then format it

A usage error's panel is as wide as the terminal and wraps its message where Rich wraps
it, and Rich measures text in terminal CELLS -- a CJK character is two, a combining mark
is none. Those widths come from a generated Unicode table inside Rich, so the TypeScript
CLI carries the same table rather than a second opinion about East Asian width: this
script copies it, and `test/cli/rich.test.ts` fails when the copy's DATA and the installed
Rich's disagree -- the data, not the text, because the file is formatted by prettier.
The table is the one Rich's `"auto"` resolves to when UNICODE_VERSION is unset.
"""
from __future__ import annotations

import importlib.metadata
import pathlib
import subprocess

from rich._unicode_data import load

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / "src" / "cli" / "rich-cells.ts"


def render() -> str:
    table = load("latest")
    rows = "\n".join(f"  [{start}, {end}, {width}]," for start, end, width in table.widths)
    wide = ", ".join(str(ord(ch)) for ch in sorted(table.narrow_to_wide))
    return f"""/**
 * GENERATED by `.venv/bin/python legacy/tools/rich_cells.py` from Rich
 * {importlib.metadata.version("rich")}'s cell-width table for Unicode {table.unicode_version}. Do not edit:
 * regenerate. `test/cli/rich.test.ts` holds this copy to the installed Rich.
 */

/** Inclusive code point ranges and the cells each character in them occupies. */
export const CELL_WIDTHS: readonly (readonly [number, number, number])[] = [
{rows}
];

/** Characters that VARIATION SELECTOR-16 widens from one cell to two. */
export const NARROW_TO_WIDE: ReadonlySet<number> = new Set([{wide}]);

export const UNICODE_VERSION = {table.unicode_version!r};
"""


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8")
    subprocess.run([str(ROOT / "node_modules" / ".bin" / "prettier"), "--write", str(TARGET)],
                   check=True, capture_output=True)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
