"""The Kubernetes seam, split into one module per subject.

Twenty-four modules under `tools/move-table.json`'s reviewed map, in tiers k0-k4 that
cannot import upward. This file is the COMPATIBILITY SURFACE and holds no code of its
own: `houston.services.k8s.create_workspace` and the other 290 names still resolve,
because call sites across `lifecycle/`, `doctor/`, `cli/` and `web/` reach them that way
and a decomposition is not the place to rewrite those.

**`__getattr__` deliberately does NOT cache**, for the same reason `services/lifecycle`
does not: the suite patches the OWNING module while production reads `k8s.<name>`, so
the façade has to re-resolve on every access or the patch is invisible. 145 sites patch
`k8s.run` alone.

**Nothing in the suite may patch this module.** `monkeypatch.undo()` restores by writing
a REAL attribute into this module's dict, which permanently shadows `__getattr__` -- and
from then on a patch on the owning module is invisible to every later test in the
process. `tools/move_table.py --repoint-tests` keeps the patches pointed at owners and a
guard fails the build on any that remain.

**Two import shapes inside the package, and the difference is deliberate.** VALUES --
the dataclasses and the constants -- are imported by name; nothing patches a name. FUNCTIONS
are reached through their MODULE, because a function bound into the importing module's
globals is a function a patch on the owner cannot reach, and 145 sites patch `k8s.run`
alone. It is also what TypeScript emits for a cross-module call (`exec_1.run()`).

**Seven modules are imported under an alias, and that is not decoration.** `context` is a
local variable in 52 functions of this seam, `namespace` in 25, and `manifests`, `names`,
`release` and `status` in one or two each -- a module shadowed by a local is a module
those functions cannot reach. So: `kubectx`, `kubens`, `kubedocs`, `vocab`, `kuberelease`,
`kubestatus`, and `kubeexec` for `exec`, which is also a builtin.

**Lazy, not imported.** Importing `houston.services.k8s.names` runs this file first, and
the submodules import each other -- so a static import here would close a cycle.
`tools/scc_check.py` gates it.
"""
