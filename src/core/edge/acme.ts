/**
 * Certificates: the local ones houston signs, and the ACME store Traefik keeps.
 *
 * Tier 2 of `src/core/edge/`.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';

import { ValidationError } from '../../lib/errors';
import { joinPath } from '../../lib/home';
import { foldCase, splitFields, splitTextLines } from '../../lib/format';
import { atomicWrite } from '../runner/paths';
import { ACME_FILE, ACME_FILE_STAGING, acmeDir } from '../tls';
import { issueLeaf } from '../tls-local';

import { composeCapture } from './engine';
import * as paths from './paths';

/**
 * Put a locally-signed certificate for `host` where the edge can serve it.
 *
 * This is what lets `--https` and `--domain` be the SAME path: they differ only in where
 * the certificate comes from -- houston's own CA, or Let's Encrypt -- and both end up as
 * one route on one port. Before, a local-CA workspace ran its own Traefik on an allocated
 * port, so ten of them ate ten ports and each got a different URL; now every one of them
 * answers on 443 by hostname.
 */
export async function issueLocalCert(host: string): Promise<void> {
  const [certPem, keyPem] = await issueLeaf(host);
  fs.mkdirSync(paths.certsDir(), { recursive: true });
  // WRITABLE? Docker creates a bind-mount target that does not exist, and it creates it
  // as root -- so on a box where the edge started before any local certificate was
  // issued, `edge/certs` is root-owned while `edge/dynamic` is not. The declaration then
  // lands and the certificate does not, and Traefik retries the pair for ever:
  //
  //     Unable to append certificate /etc/traefik/certs/<host>.crt to store
  //     error="tls: failed to find any PEM data in certificate input"
  //
  // Observed on a live box with two such orphans, logging once a second and serving
  // nothing for either name. It is a fixable environment fault and says so.
  try {
    fs.accessSync(paths.certsDir(), fs.constants.W_OK);
  } catch {
    throw new ValidationError(
      `cannot write certificates into ${paths.certsDir()} — it is not writable by this ` +
        'user, so the name would be declared and never served.\n' +
        '  Docker creates a missing bind-mount target as root. Give it back:\n' +
        `    sudo chown -R $(id -u):$(id -g) ${paths.certsDir()}`,
    );
  }
  // And the watched directory: this writes the certificate DECLARATION into it, and on
  // the first `up --https` of a box that has no edge yet, nothing has created it.
  // `atomicWrite` puts its temp file beside the target, so a missing parent is an error
  // -- `up --https` crashed outright.
  fs.mkdirSync(paths.dynamicDir(), { recursive: true });
  await atomicWrite(joinPath(paths.certsDir(), `${host}.crt`), certPem);
  // 0600 on the KEY, set on the temp file so the target never exists world-readable.
  // This landed at the umask (typically 0644) on a box whose `~/.houston` is only
  // tightened to 0700 by `serve` or a config save -- neither of which runs on a CLI-only
  // `up --https`.
  await atomicWrite(joinPath(paths.certsDir(), `${host}.key`), keyPem, { mode: 0o600 });
  // Checked, because the declaration written below is what makes an absent certificate a
  // permanent error loop rather than a missing file nobody references.
  for (const part of ['crt', 'key']) {
    if (fs.statSync(joinPath(paths.certsDir(), `${host}.${part}`)).size === 0) {
      throw new ValidationError(
        `the ${part} for ${host} was written empty to ${paths.certsDir()} — Traefik would ` +
          "log 'failed to find any PEM data' for it for ever. Check the space and " +
          'permissions on that directory.',
      );
    }
  }
  // Declared in the watched directory, so Traefik picks it up like any route.
  await atomicWrite(
    joinPath(paths.dynamicDir(), `_cert-${host}.yml`),
    '# Generated by houston. Do not edit by hand.\n' +
      'tls:\n' +
      '  certificates:\n' +
      `    - certFile: /etc/traefik/certs/${host}.crt\n` +
      `      keyFile: /etc/traefik/certs/${host}.key\n`,
  );
}

/** Whether the running configuration declares a certificate resolver. */
export function hasAcme(): boolean {
  try {
    return fs.readFileSync(paths.composePath(), 'utf8').includes('certificatesresolvers');
  } catch {
    return false;
  }
}

/**
 * A terminal colour escape, built from its code point rather than written literally.
 *
 * ESC is a control character, and a control character in a source file is one an editor
 * or a formatter can normalise away -- at which point this would silently stop stripping
 * anything and `acmeFailure` would go back to returning the whole unreadable line, which
 * is exactly the defect it was written to fix. Found doing it: the literal was eaten
 * once already while this module was being written.
 */
const ANSI = new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, 'gu');

/**
 * The last ACME failure the edge logged, for `domain` or for anything, or ''.
 *
 * Traefik requests certificates in the BACKGROUND after it starts, so the edge comes up
 * healthy, the route loads, `serve` prints an https URL -- and issuance can be failing
 * with nobody told. Reported exactly that way: a GUI whose name served nothing, while the
 * reason sat in a container log there was no command to read.
 *
 * The reason is worth extracting rather than pointing at, because it is usually conclusive
 * and short:
 *
 *     DNS problem: NXDOMAIN looking up A for <name> - check that a DNS record exists
 */
export async function acmeFailure({ domain = '', tail = 400 } = {}): Promise<string> {
  let out = await composeCapture(['logs', `--tail=${String(tail)}`]);
  if (out === '') return '';
  // ANSI FIRST. Traefik colours its own output, so the marker below is really
  // `\x1b[36merror=\x1b[0m\x1b[31m\x1b[1m"` and a literal match finds nothing -- which is
  // how the first version of this returned the whole unreadable line.
  out = out.replace(ANSI, '');
  let hit = '';
  for (const line of splitTextLines(out)) {
    if (!line.toLowerCase().includes('acme')) continue;
    const low = line.toLowerCase();
    if (!low.includes('unable to obtain') && !low.includes('error')) continue;
    if (domain !== '' && !line.includes(domain)) continue;
    hit = line;
  }
  if (hit === '') return '';
  // Traefik logs one long structured line; the useful part is the quoted error.
  const marker = 'error="';
  if (hit.includes(marker)) {
    hit = (hit.split(marker)[1] ?? '').split('"')[0] ?? '';
  }
  // Every literal `\n` a space, the words (`splitFields`) joined by single spaces, and 400 CODE
  // POINTS kept, where `slice` cut 400 UTF-16 units -- half as many emoji, ending in a lone
  // surrogate.
  return Array.from(splitFields(hit.split('\\n').join(' ')).join(' '))
    .slice(0, 400)
    .join('');
}

/**
 * Hostnames declared to the edge whose certificate file is missing or empty.
 *
 * Each one is a name that will never serve and an error Traefik repeats for ever, so it
 * belongs in `status` rather than only in a log nobody was told about.
 */
export function orphanCerts(): string[] {
  const out: string[] = [];
  let entries: string[];
  try {
    entries = fs.readdirSync(paths.dynamicDir());
  } catch {
    return out;
  }
  for (const entry of entries.sort()) {
    if (!entry.startsWith('_cert-') || !entry.endsWith('.yml')) continue;
    const host = entry.slice('_cert-'.length, -'.yml'.length);
    const crt = joinPath(paths.certsDir(), `${host}.crt`);
    try {
      if (!fs.statSync(crt).isFile() || fs.statSync(crt).size === 0) out.push(host);
    } catch {
      out.push(host);
    }
  }
  return out;
}

// --- forgetting a name -------------------------------------------------------------
// `deregister` removes a ROUTE, which is all a teardown needs: the name stops answering.
// It is not all a teardown LEAVES. Route files are keyed by workspace name and
// certificate material by HOSTNAME, so `down --volumes` unlinked `dynamic/<name>.yml` and
// walked past `certs/<host>.crt`, its private key, the `_cert-<host>.yml` that loads them,
// and -- for a real `--domain` -- a Let's Encrypt certificate and key sitting in Traefik's
// ACME store for ever.
//
// `orphanCerts` reported nothing because it flags a declaration whose certificate is
// MISSING, which is the opposite failure -- there everything was present and valid, just
// unreachable. The visible symptom is a TLS handshake that succeeds, with a genuine
// certificate for the name, into a 404.

/**
 * Both ACME stores, whichever exist.
 *
 * Staging and production are SEPARATE files and a host can be in either -- `config set
 * acme.staging false` after a staging issuance leaves the staging entry behind. A delete
 * that looked only at the live one would report success and leave a key on disk.
 */
export function acmeStores(): string[] {
  return [joinPath(acmeDir(), ACME_FILE), joinPath(acmeDir(), ACME_FILE_STAGING)].filter(
    (target) => {
      try {
        return fs.statSync(target).isFile();
      } catch {
        return false;
      }
    },
  );
}

/**
 * Traefik's store as an object, or `{}` -- never an exception.
 *
 * A store Traefik has not written yet is empty, and a half-written or hand-edited one is
 * not this function's problem to diagnose: both mean "no certificate for that host in
 * here", which is the only question being asked.
 */
export function acmeRead(target: string): Record<string, unknown> {
  try {
    const doc: unknown = JSON.parse(fs.readFileSync(target, 'utf8'));
    return doc !== null && typeof doc === 'object' && !Array.isArray(doc)
      ? (doc as Record<string, unknown>)
      : {};
  } catch {
    return {};
  }
}

export function acmeNames(cert: Record<string, unknown>): string[] {
  const raw = cert.domain;
  const dom =
    raw !== null && typeof raw === 'object' && !Array.isArray(raw)
      ? (raw as Record<string, unknown>)
      : {};
  const sans = Array.isArray(dom.sans) ? dom.sans : [];
  return [String(dom.main ?? ''), ...sans.map((entry) => String(entry))]
    .filter((name) => name !== '')
    .map((name) => foldCase(name));
}

/**
 * Every hostname the ACME stores hold a certificate for.
 *
 * Read from the store rather than from the routes, deliberately: a certificate OUTLIVES
 * the route that asked for it, and this exists to find the ones nothing points at any
 * more.
 */
export function acmeHosts(): string[] {
  const out = new Set<string>();
  for (const target of acmeStores()) {
    for (const resolver of Object.values(acmeRead(target))) {
      if (resolver === null || typeof resolver !== 'object') continue;
      const certs = (resolver as Record<string, unknown>).Certificates;
      if (!Array.isArray(certs)) continue;
      for (const cert of certs) {
        if (cert !== null && typeof cert === 'object') {
          for (const name of acmeNames(cert as Record<string, unknown>)) out.add(name);
        }
      }
    }
  }
  return [...out].sort();
}

/**
 * Drop `host`'s certificate AND private key from Traefik's ACME stores.
 *
 * Returns the store filenames it came out of, so a caller can say what happened rather
 * than claiming a deletion it did not make.
 *
 * The ACME **Account** is kept. It is a registration with Let's Encrypt, not a certificate
 * -- dropping it makes the next issuance register a new key pair for no benefit, and
 * account registrations have their own rate limit.
 *
 * Written 0600 because what is being rewritten is a file full of private keys, and an
 * atomic write would otherwise create it 0644 from the umask.
 */
export async function forgetAcme(host: string): Promise<string[]> {
  if (host === '') return [];
  const want = foldCase(host);
  const gone: string[] = [];
  for (const target of acmeStores()) {
    const doc = acmeRead(target);
    let touched = false;
    for (const resolver of Object.values(doc)) {
      if (resolver === null || typeof resolver !== 'object') continue;
      const holder = resolver as Record<string, unknown>;
      const certs = holder.Certificates;
      if (!Array.isArray(certs)) continue;
      const keep = certs.filter(
        (cert) =>
          !(
            cert !== null &&
            typeof cert === 'object' &&
            acmeNames(cert as Record<string, unknown>).includes(want)
          ),
      );
      if (keep.length !== certs.length) {
        holder.Certificates = keep;
        touched = true;
      }
    }
    if (touched) {
      await atomicWrite(target, JSON.stringify(doc, null, 2), { mode: 0o600 });
      gone.push(path.basename(target));
    }
  }
  return gone;
}
