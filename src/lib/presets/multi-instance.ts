/**
 * Dynamic `multi-instance` preset: N Rocket.Chat instances behind Traefik, sharing one
 * MongoDB replica set and coordinating over NATS.
 *
 * Reproduces horizontal-scaling tickets -- cross-instance real-time, presence, and
 * sticky-session / websocket issues. Modelled on the official RocketChat/rocketchat-compose
 * (compose.nats.yml + compose.traefik.yml):
 *
 *   * Instances talk to each other over NATS (the moleculer transporter), so the legacy
 *     INSTANCE_IP DDP mesh is not used.
 *   * Traefik load-balances via its FILE provider -- a `dynamic.yml` listing the backend
 *     instances. Upstream generates that file from ROCKETCHAT_BACKEND_SERVERS with an
 *     init container; we know the instance count at build time, so we generate it
 *     directly here (no init container, no Docker-socket dependency).
 *
 * The heavy lifting (cloning rocketchat into rocketchat-1..N, wiring the NATS transporter,
 * handing Traefik the published host port) happens in `compose.build`, because the RC
 * image, env and host port are not known until `up`.
 *
 * Parameters (via `--set`):
 *   instances   number of Rocket.Chat instances to run (default 2, clamped 2..5).
 */
import { TRAEFIK_TAG } from '../config';
import { intParam } from './common';
import { type Params, register } from './registry';
import { emptyPreset, type Preset } from './types';

// Pinned to match the official rocketchat-compose defaults (multi-arch; verify with
// `docker manifest inspect` before release, as with the Mongo images). Traefik is
// `config.TRAEFIK_TAG`, shared with the HTTPS edge.
const NATS_TAG = '2.11-alpine';

/**
 * Traefik file-provider config: one load-balancer service fronting the N instances, with
 * a sticky cookie so a client's websocket (DDP) stays pinned to one instance instead of
 * being bounced mid-session.
 */
function dynamicConfig(n: number): string {
  const servers: string[] = [];
  for (let i = 1; i <= n; i += 1)
    servers.push(`          - url: "http://rocketchat-${String(i)}:3000"`);
  return (
    '# Generated by houston. Do not edit by hand -- re-run `houston up`.\n' +
    '# Traefik file provider: load-balance across the rocketchat-1..N instances.\n' +
    'http:\n' +
    '  routers:\n' +
    '    rocketchat:\n' +
    '      rule: "PathPrefix(`/`)"\n' +
    '      entryPoints: [web]\n' +
    '      service: rocketchat\n' +
    '  services:\n' +
    '    rocketchat:\n' +
    '      loadBalancer:\n' +
    '        healthCheck:\n' + // only route to instances serving /api/info
    '          path: /api/info\n' +
    '          interval: "10s"\n' +
    '          timeout: "5s"\n' +
    '        sticky:\n' +
    '          cookie:\n' +
    '            name: rc_lb\n' +
    '        servers:\n' +
    `${servers.join('\n')}\n`
  );
}

export function build(params: Params): Preset {
  const instances = Math.max(2, Math.min(5, intParam(params, 'instances', 2)));

  const services: Record<string, Record<string, unknown>> = {
    // Inter-instance message broker (presence, notifications, streaming).
    nats: {
      image: `docker.io/nats:${NATS_TAG}`,
      restart: 'unless-stopped',
      command: ['--http_port', '8222'],
    },
    // Reverse proxy / load balancer. File provider reads the generated dynamic.yml
    // (mounted below); compose.build injects the published host port as `<host>:80` via
    // entry_service.
    traefik: {
      image: `docker.io/traefik:${TRAEFIK_TAG}`,
      restart: 'unless-stopped',
      command: [
        '--providers.file.filename=/etc/traefik/dynamic.yml',
        '--providers.file.watch=true',
        '--entryPoints.web.address=:80',
      ],
      volumes: ['./traefik/dynamic.yml:/etc/traefik/dynamic.yml:ro'],
    },
  };

  return {
    ...emptyPreset('multi-instance'),
    description:
      `${String(instances)} Rocket.Chat instances behind Traefik, sharing one Mongo ` +
      'replica set and NATS. Reproduce horizontal-scaling / real-time-across-' +
      'instances tickets.',
    env: {}, // per-instance env (TRANSPORTER) is added by compose.build
    services,
    dependsOn: ['nats'], // every instance also depends on mongo (added by compose)
    instances, // tells compose.build to clone rocketchat-1..N
    entryService: 'traefik', // tells compose.build to hand the host port to Traefik
    requiresLicense: false,
    source: 'built-in (dynamic)',
    files: [['traefik/dynamic.yml', dynamicConfig(instances)]],
    paramsHelp: { instances: 'number of Rocket.Chat instances (default 2, max 5)' },
    notes: [
      'Verify the mesh (lists every connected instance; one a restart replaced stays listed a while):',
      '    houston api --name <name> GET /api/v1/instances.get',
      'Cross-instance real-time needs an Enterprise license (its scalability module): without one,',
      '  a message posted on one instance shows on the others only after a reload. Add one with',
      '  `--license` or in Rocket.Chat under Workspace > Subscription, then open two instance URLs',
      '  (shown above) in separate browsers and post in one.',
    ],
  };
}

register('multi-instance', build);
